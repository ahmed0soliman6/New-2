/**
 * Normalizes Arabic & English text for drug comparison:
 * - Removes Arabic diacritics (tashkeel) and tatweel
 * - Unifies Alef variants (أ إ آ ٱ -> ا), Teh Marbuta (ة -> ه), Yeh variants (ى ئ -> ي), Waw (ؤ -> و)
 * - Unifies Persian/loan letters (پ -> ب, ڤ -> ف, چ -> ج, گ -> ج)
 * - Lowercases English characters and collapses punctuation/spaces
 */
export function normalizeDrugText(input: string): string {
  if (!input) return '';
  return input
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670\u0640]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/[ىئ]/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/پ/g, 'ب')
    .replace(/ڤ/g, 'ف')
    .replace(/[چگ]/g, 'ج')
    .replace(/[^\p{L}\p{N}\s./+-]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Converts either Arabic OR English drug terms into a unified phonetic consonant/vowel skeleton
 * so that searching in Arabic (e.g., "بيتاك", "كونكور", "اموكسيسيلين", "سوتالول", "باراسيتامول")
 * matches English drug names ("Betacor", "Concor", "Amoxicillin", "Sotalol", "Paracetamol")
 * and vice versa even when only one language is stored!
 */
export function toPhoneticSkeleton(input: string): string {
  const norm = normalizeDrugText(input);
  if (!norm) return '';

  // Map English digraphs first
  let s = norm
    .replace(/ph/g, 'f')
    .replace(/sh/g, 'ش')
    .replace(/ch/g, 'ش')
    .replace(/th/g, 'ت')
    .replace(/kh/g, 'خ')
    .replace(/gh/g, 'غ')
    .replace(/qu/g, 'k')
    .replace(/ck/g, 'k')
    .replace(/x/g, 'ks')
    .replace(/c(?=[eiy])/g, 's')
    .replace(/c/g, 'k');

  const charMap: Record<string, string> = {
    // Arabic to phonetic code
    'ا': 'a',
    'ب': 'b',
    'ت': 't',
    'ث': 's',
    'ج': 'g',
    'ح': 'h',
    'خ': 'kh',
    'د': 'd',
    'ذ': 'z',
    'ر': 'r',
    'ز': 'z',
    'س': 's',
    'ش': 'sh',
    'ص': 's',
    'ض': 'd',
    'ط': 't',
    'ظ': 'z',
    'ع': 'a',
    'غ': 'gh',
    'ف': 'f',
    'ق': 'k',
    'ك': 'k',
    'ل': 'l',
    'م': 'm',
    'ن': 'n',
    'ه': 'h',
    'و': 'o',
    'ي': 'i',
    'ء': '',
    // English to phonetic code
    a: 'a',
    b: 'b',
    d: 'd',
    e: 'i',
    f: 'f',
    g: 'g',
    h: 'h',
    i: 'i',
    j: 'g',
    k: 'k',
    l: 'l',
    m: 'm',
    n: 'n',
    o: 'o',
    p: 'b',
    q: 'k',
    r: 'r',
    s: 's',
    t: 't',
    u: 'o',
    v: 'f',
    w: 'o',
    y: 'i',
    z: 'z',
  };

  let out = '';
  for (const ch of s) {
    if (charMap[ch] !== undefined) {
      out += charMap[ch];
    } else if (/[0-9]/.test(ch)) {
      out += ch;
    } else if (ch === ' ') {
      out += ' ';
    }
  }

  // Collapse repeated adjacent letters (e.g. "ll" -> "l", "ii" -> "i")
  return out.replace(/(.)\1+/g, '$1').trim();
}

/**
 * Strips all vowel codes (a, i, o) except the leading character of each word
 * for resilient consonant-skeleton matching across Arabic & English drug spellings
 */
export function toConsonantSkeleton(input: string): string {
  const ph = toPhoneticSkeleton(input);
  if (!ph) return '';
  return ph
    .split(' ')
    .map((word) => {
      if (word.length <= 2) return word;
      return word[0] + word.slice(1).replace(/[aio]/g, '');
    })
    .join(' ');
}

